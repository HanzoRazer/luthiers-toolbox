#!/usr/bin/env python3
"""Rebuild the four replay programs from pinned history and check their hashes.

The full programs are NOT committed: they are machine-executable G-code, and two
of them carry the 702 rapids below Z0. Each one is fully determined by a pinned
commit plus (arms D and E) the archived orchestrator/machines pair that is
already in the repository. This tool rebuilds them outside the repository and
compares each SHA-256 with ``EVIDENCE.json``, then re-runs the motion parser on
the rebuilt programs and requires ``replay/results/metrics.json`` to come back
byte for byte. It exits 1 on any mismatch.

Needs a clone with full history (the two tree commits must be present) and the
Python dependencies of ``services/api``. Offline: no network, no machine, no
application startup beyond importing the historical neck generator.

    python -I docs/investigations/cam-orchestrator-recovery_2026-10-14/replay/regenerate_programs.py \
        --work-dir <tmp outside the repo> [--excerpts <path>]

``--excerpts`` also writes the line excerpts committed as
``replay/results/EXCERPTS.md``.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUNDLE = HERE.parent
REPO = BUNDLE.parents[2]
ARCHIVED = REPO / "docs" / "archive" / "photo_vectorizer_patches"
PARSER = REPO / "scripts" / "investigations" / "neck_gcode_motion_metrics.py"

PRE_P1 = "9c5f46a95af3bc4b983fa30d1328b530f08c520c"
BASE = "d42712e0e358b2344ddc046e83f169233581dce5"
#: arm -> (tree commit, overlay the archived orchestrator + machines pair)
ARMS = {
    "A_pre_p1": (PRE_P1, False),
    "B_live": (BASE, False),
    "D_bundle_as_shipped": (BASE, True),
    "E_bundle_on_pre_p1": (PRE_P1, True),
}
CONTEXT_BEFORE, CONTEXT_AFTER = 3, 1


def _extract(commit: str, dest: Path) -> None:
    blob = subprocess.run(["git", "-C", str(REPO), "archive", commit, "services/api/app"],
                          capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(blob)) as tar:
        tar.extractall(dest, filter="data")


def _excerpt(arm: str, lines: list[str], metrics: dict) -> list[str]:
    m = metrics["arms"][arm]
    out = [f"## {arm}", "",
           f"- SHA-256 `{m['sha256']}`, {m['total_lines']} lines",
           f"- G0 with XY motion below Z0: **{m['g0_xy_below_plane']}**; tool changes: **{m['tool_change_count']}**",
           ""]

    def block(title: str, centre: int, before: int = CONTEXT_BEFORE, after: int = CONTEXT_AFTER) -> None:
        lo, hi = max(1, centre - before), min(len(lines), centre + after)
        out.extend([f"{title} (line {centre}):", "", "```"])
        out.extend(f"{n:>5}  {lines[n - 1]}" for n in range(lo, hi + 1))
        out.extend(["```", ""])

    first = m["first_violation_lines"]
    if first:
        block("First rapid below Z0, depth inherited from the preceding G1", first[0], before=4, after=4)
        out.extend([f"Next rapids below Z0 at lines {', '.join(map(str, first[1:]))} "
                    f"(first {len(first)} of {m['g0_xy_below_plane']}).", ""])
    for tc in m["tool_changes"]:
        block(f"Tool change T{tc['tool']} ({tc['op'] or 'preamble'}, Z at change {'unknown' if tc['z_at_change'] is None else tc['z_at_change']})", tc["line"])
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work-dir", type=Path, required=True)
    ap.add_argument("--excerpts", type=Path)
    args = ap.parse_args(argv)
    work = args.work_dir.resolve()
    if work == REPO or REPO in work.parents:
        print("refused: --work-dir must be outside the repository", file=sys.stderr)
        return 2

    evidence = json.loads((BUNDLE / "EVIDENCE.json").read_text(encoding="utf-8"))
    metrics = json.loads((HERE / "results" / "metrics.json").read_text(encoding="utf-8"))
    out_dir = work / "out"
    out_dir.mkdir(parents=True, exist_ok=True)
    failures, excerpt = [], ["# Replay program excerpts", "",
                             "Generated by `replay/regenerate_programs.py --excerpts`. The full programs are not",
                             "committed; rebuild them with that tool. Each excerpt is pinned to its program's SHA-256.", ""]
    for arm, (commit, overlay) in ARMS.items():
        tree = work / arm
        if tree.exists():
            shutil.rmtree(tree)
        _extract(commit, tree)
        if overlay:
            shutil.copyfile(ARCHIVED / "orchestrator.py", tree / "services/api/app/cam/neck/orchestrator.py")
            shutil.copyfile(ARCHIVED / "machines.py", tree / "services/api/app/cam/machines.py")
        run = subprocess.run([sys.executable, "-I", str(HERE / "generate_arm.py"), "--tree",
                              str(tree / "services/api"), "--arm", arm, "--out-dir", str(out_dir)],
                             cwd=work, capture_output=True, text=True)
        program = out_dir / f"{arm}.nc"
        if run.returncode != 0 or not program.exists():
            failures.append(f"{arm}: generator exit {run.returncode}: {run.stderr.strip()[-300:]}")
            continue
        actual = hashlib.sha256(program.read_bytes()).hexdigest()
        expected = evidence["arms"][arm]["program_sha256"]
        print(f"{arm}: {'MATCH' if actual == expected else 'MISMATCH'} {actual}")
        if actual != expected:
            failures.append(f"{arm}: sha256 {actual} != recorded {expected}")
        excerpt += _excerpt(arm, program.read_text(encoding="utf-8").splitlines(), metrics)
        shutil.copyfile(program, out_dir / f"{arm}.gcode.evidence")  # the name metrics.json records

    if not failures:
        report = out_dir / "metrics.json"
        run = subprocess.run([sys.executable, "-I", str(PARSER), "--plane-z", "0.0", "--out", str(report),
                              *(f"{arm}={out_dir / f'{arm}.gcode.evidence'}" for arm in ARMS)],
                             capture_output=True, text=True)
        committed = (HERE / "results" / "metrics.json").read_bytes().replace(b"\r\n", b"\n")
        if run.returncode != 0 or report.read_bytes() != committed:
            failures.append(f"metrics.json does not reproduce (parser exit {run.returncode})")
        else:
            print("metrics.json: MATCH")

    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 1
    if args.excerpts:
        args.excerpts.write_text("\n".join(excerpt).rstrip() + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
